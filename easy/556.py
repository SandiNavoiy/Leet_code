class Solution:
    def nextGreaterElement(self, n: int) -> int:
        s = list(str(n))
        length = len(s)

        # 1. Ищем первую позицию слева, где цифра меньше следующей (справа налево)
        i = length - 2
        while i >= 0 and s[i] >= s[i + 1]:
            i -= 1

        if i == -1:
            return -1  # следующее число невозможно

        # 2. Ищем самую правую цифру, которая больше s[i]
        j = length - 1
        while s[j] <= s[i]:
            j -= 1

        # 3. Меняем их местами (оба элемента — строки, ничего не конвертируем в int)
        s[i], s[j] = s[j], s[i]

        # 4. Разворачиваем хвост после позиции i, чтобы получить минимально возможное число
        s[i + 1:] = reversed(s[i + 1:])

        res_str = ''.join(s)
        res = int(res_str)

        # 5. Проверка на 32-битное знаковое целое
        if res > 2**31 - 1:
            return -1

        return res


